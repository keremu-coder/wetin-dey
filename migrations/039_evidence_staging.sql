-- Migration 039: staging bucket for signed uploads + missing community-media bucket.
--
-- Fix 1 (App Store submission): /api/reports accepts up to 25MB, /api/communities/
-- [slug]/messages up to 15MB. Vercel caps incoming request bodies at 4.5MB.
-- Any larger upload throws 413 before the route handler runs.
--
-- Solution: client uploads directly to Supabase Storage via a signed URL
-- issued by the server, then POSTs the resulting storage path to the main
-- route. The server downloads from staging, strips metadata, moves to the
-- final public/private bucket, then deletes the staging object.
--
-- Two consequences:
--   1. Evidence files land in a private staging bucket first. This prevents
--      a URL leak during the strip-and-verify window.
--   2. community-media is missing from every prior migration - it is
--      referenced by app/api/communities/[slug]/messages/route.ts (photo/
--      video attachments in private spaces) and by
--      app/api/community-messages/[id]/view/route.ts. Adding it here so a
--      fresh clone can reproduce production.
--
-- Idempotent: safe to re-run.

insert into storage.buckets (id, name, public)
values ('evidence-staging', 'evidence-staging', false)
on conflict (id) do update set public = false;

insert into storage.buckets (id, name, public)
values ('community-media', 'community-media', false)
on conflict (id) do update set public = false;

-- evidence-staging: accepts every MIME that can legitimately go through
-- either /api/reports/upload or /api/communities/[slug]/upload. Per-kind
-- checks live in the routes; this is the storage-layer backstop.
update storage.buckets
  set file_size_limit = 26214400,  -- 25 MiB
      allowed_mime_types = array[
        'image/jpeg','image/png','image/webp','image/heic','image/gif',
        'video/mp4','video/quicktime','video/webm',
        'audio/mp4','audio/mpeg','audio/webm','audio/ogg','audio/wav'
      ]
where id = 'evidence-staging';

-- community-media: photos and videos only, 15 MiB hard cap (matches
-- MAX_VIDEO in the community messages route).
update storage.buckets
  set file_size_limit = 15728640,  -- 15 MiB
      allowed_mime_types = array[
        'image/jpeg','image/png','image/webp',
        'video/mp4','video/quicktime','video/webm'
      ]
where id = 'community-media';

-- No anon/authenticated policies: both buckets are service-role only.
-- Client writes go through signed upload URLs; reads go through signed
-- read URLs generated by the server. Exactly like dm-media (035).